from __future__ import annotations

import argparse
import sys
from collections import Counter
from pathlib import Path
from typing import Any

import matplotlib.pyplot as plt
import torch
from torch.utils.data import DataLoader

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from model.torch_sign_frames_dataset import SignFramesDataset


def collate_sign_batch(batch: list[dict[str, Any]]) -> dict[str, Any]:
    videos = torch.stack([x["video"] for x in batch], dim=0)
    labels = torch.stack([x["label"] for x in batch], dim=0)
    indices = torch.stack([x["indices"] for x in batch], dim=0)

    return {
        "video": videos,
        "label": labels,
        "indices": indices,
        "label_name": [x["label_name"] for x in batch],
        "frames_path": [x["frames_path"] for x in batch],
        "split": [x["split"] for x in batch],
        "raw_num_frames": [x["raw_num_frames"] for x in batch],
        "applied_augs": [x["applied_augs"] for x in batch],
    }


def save_clip_preview(sample: dict[str, Any], out_path: Path) -> None:
    """Save a 5-frame preview grid for a single sample."""
    video = sample["video"].squeeze(0)  # [T, H, W]
    t = int(video.shape[0])
    picks = [0, t // 4, t // 2, (3 * t) // 4, t - 1]

    fig, axes = plt.subplots(1, 5, figsize=(15, 3))
    for ax, idx in zip(axes, picks):
        frame = video[idx].cpu().numpy()
        ax.imshow(frame, cmap="gray", vmin=0.0, vmax=1.0)
        ax.set_title(f"t={idx}")
        ax.axis("off")

    fig.suptitle(
        f"label={sample['label_name']} | raw={sample['raw_num_frames']} | augs={','.join(sample['applied_augs']) or 'none'}",
        fontsize=10,
    )
    fig.tight_layout()
    out_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_path, dpi=140)
    plt.close(fig)


def describe_batch(batch: dict[str, Any], name: str) -> None:
    print(f"\n[{name}] batch video shape: {tuple(batch['video'].shape)}")
    print(f"[{name}] batch label shape: {tuple(batch['label'].shape)}")

    label_counts = Counter(batch["label"].tolist())
    print(f"[{name}] label ids in first batch: {dict(label_counts)}")

    aug_preview = batch["applied_augs"][:5]
    print(f"[{name}] first 5 augmentation tuples: {aug_preview}")


def main() -> None:
    parser = argparse.ArgumentParser(description="Demo usage of SignFramesDataset + DataLoader")
    parser.add_argument(
        "--csv",
        type=str,
        default=str(PROJECT_ROOT / "merged_datasets" / "split8c_frames_signer_disjoint.csv"),
        help="Path to split CSV generated by notebook 8c.",
    )
    parser.add_argument("--sequence-length", type=int, default=64)
    parser.add_argument("--batch-size", type=int, default=8)
    parser.add_argument("--num-workers", type=int, default=0)
    parser.add_argument("--sampler-power", type=float, default=0.5)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    csv_path = Path(args.csv)
    if not csv_path.exists():
        raise FileNotFoundError(f"CSV not found: {csv_path}")

    print("Using CSV:", csv_path)

    train_ds = SignFramesDataset(
        csv_path=csv_path,
        project_root=PROJECT_ROOT,
        split="train",
        mode="train",
        sequence_length=args.sequence_length,
        base_seed=args.seed,
    )

    val_ds = SignFramesDataset(
        csv_path=csv_path,
        project_root=PROJECT_ROOT,
        split="val",
        mode="val",
        sequence_length=args.sequence_length,
        label_to_index=train_ds.label_to_index,
        base_seed=args.seed,
    )

    test_ds = SignFramesDataset(
        csv_path=csv_path,
        project_root=PROJECT_ROOT,
        split="test",
        mode="test",
        sequence_length=args.sequence_length,
        label_to_index=train_ds.label_to_index,
        base_seed=args.seed,
    )

    print("Dataset sizes:")
    print("  train:", len(train_ds))
    print("  val  :", len(val_ds))
    print("  test :", len(test_ds))
    print("Num classes:", len(train_ds.label_to_index))

    # Epoch-dependent sampling/augmentation demo for the same index.
    train_ds.set_epoch(0)
    sample_e0 = train_ds[0]
    train_ds.set_epoch(1)
    sample_e1 = train_ds[0]

    same_indices = torch.equal(sample_e0["indices"], sample_e1["indices"])
    print("\nSame sample at epoch 0 vs 1:")
    print("  raw_num_frames:", sample_e0["raw_num_frames"], "->", sample_e1["raw_num_frames"])
    print("  applied_augs  :", sample_e0["applied_augs"], "->", sample_e1["applied_augs"])
    print("  temporal indices identical:", same_indices)

    sampler = train_ds.build_weighted_sampler(power=args.sampler_power, replacement=True)

    train_loader = DataLoader(
        train_ds,
        batch_size=args.batch_size,
        sampler=sampler,
        num_workers=args.num_workers,
        pin_memory=torch.cuda.is_available(),
        collate_fn=collate_sign_batch,
        drop_last=False,
    )

    val_loader = DataLoader(
        val_ds,
        batch_size=args.batch_size,
        shuffle=False,
        num_workers=args.num_workers,
        pin_memory=torch.cuda.is_available(),
        collate_fn=collate_sign_batch,
        drop_last=False,
    )

    train_batch = next(iter(train_loader))
    val_batch = next(iter(val_loader))

    describe_batch(train_batch, "train")
    describe_batch(val_batch, "val")

    artifacts = PROJECT_ROOT / "tests" / "artifacts"
    save_clip_preview(sample_e0, artifacts / "sample_train_epoch0.png")
    save_clip_preview(sample_e1, artifacts / "sample_train_epoch1.png")
    print("\nSaved previews:")
    print(" ", artifacts / "sample_train_epoch0.png")
    print(" ", artifacts / "sample_train_epoch1.png")


if __name__ == "__main__":
    main()
